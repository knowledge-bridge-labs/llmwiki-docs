#!/usr/bin/env node

import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const targetOrg = readOption('--target-org') || process.env.LLMWIKI_TARGET_ORG || 'knowledge-bridge-labs';
const teamSlug = readOption('--team') || 'maintainers';
const apply = process.argv.includes('--apply');
const owner = `@${targetOrg}/${teamSlug}`;
const repos = ['llmwiki-serve', 'llmwiki-agent-bridge', 'llmwiki-chat', 'llmwiki-docs'];
const scriptDir = dirname(fileURLToPath(import.meta.url));
const docsRepo = resolve(scriptDir, '..');
const workspaceRoot = resolve(docsRepo, '..');

function readOption(name) {
  const prefix = `${name}=`;
  const value = process.argv.find((arg) => arg.startsWith(prefix));
  return value ? value.slice(prefix.length).trim() : '';
}

function run(command, args, options = {}) {
  const result = spawnSync(command, args, {
    encoding: 'utf8',
    ...options
  });
  return {
    ok: result.status === 0,
    status: result.status ?? 1,
    stdout: result.stdout?.trim() ?? '',
    stderr: result.stderr?.trim() || result.error?.message || ''
  };
}

function fail(message, status = 1) {
  console.error(message);
  process.exit(status);
}

function codeownersContent() {
  return [
    '# Default owner for the Knowledge Bridge Labs public-preview repositories.',
    '# Generated by llmwiki-docs/scripts/sync-codeowners.mjs after org team setup.',
    `* ${owner}`,
    ''
  ].join('\n');
}

function normalizeNewlines(value) {
  return value.replace(/\r\n/g, '\n');
}

function requireCleanMain(repo, localPath) {
  const branch = run('git', ['-C', localPath, 'rev-parse', '--abbrev-ref', 'HEAD']);
  if (!branch.ok || branch.stdout !== 'main') {
    fail(`Local checkout ${repo} must be on main before applying CODEOWNERS; got ${branch.stdout || branch.stderr}.`);
  }

  const status = run('git', ['-C', localPath, 'status', '--porcelain=v1']);
  if (!status.ok) {
    fail(`Cannot read local status for ${repo}: ${status.stderr || status.stdout}`);
  }
  if (status.stdout) {
    fail(`Local checkout ${repo} has uncommitted changes. Commit, stash, or revert them before applying CODEOWNERS.`);
  }
}

const auth = run('gh', ['auth', 'status']);
if (!auth.ok) {
  fail(auth.stderr || auth.stdout || 'gh auth status failed', auth.status);
}

if (apply) {
  const team = run('gh', ['api', `orgs/${targetOrg}/teams/${teamSlug}`, '--silent']);
  if (!team.ok) {
    fail(
      `Target team ${owner} is not accessible. Run org configuration and add team access before applying CODEOWNERS.`
    );
  }
}

const content = codeownersContent();
for (const repo of repos) {
  const localPath = resolve(workspaceRoot, repo);
  const insideWorkTree = run('git', ['-C', localPath, 'rev-parse', '--is-inside-work-tree']);
  if (!insideWorkTree.ok || insideWorkTree.stdout !== 'true') {
    fail(`Local checkout missing or invalid for ${repo}: ${localPath}`);
  }

  if (apply) {
    requireCleanMain(repo, localPath);
    const access = run('gh', [
      'api',
      `orgs/${targetOrg}/teams/${teamSlug}/repos/${targetOrg}/${repo}`,
      '--silent'
    ]);
    if (!access.ok) {
      fail(`Team ${owner} does not have repository access to ${targetOrg}/${repo}.`);
    }
  }

  const codeownersPath = resolve(localPath, '.github', 'CODEOWNERS');
  const current = existsSync(codeownersPath) ? readFileSync(codeownersPath, 'utf8') : '';
  if (normalizeNewlines(current) === content) {
    console.log(`unchanged ${repo}/.github/CODEOWNERS`);
    continue;
  }

  if (!apply) {
    console.log(`would write ${repo}/.github/CODEOWNERS -> ${owner}`);
    continue;
  }

  mkdirSync(dirname(codeownersPath), { recursive: true });
  writeFileSync(codeownersPath, content, 'utf8');
  console.log(`wrote ${repo}/.github/CODEOWNERS`);
}

if (!apply) {
  console.log('\nDry run only. Rerun with --apply after the target org team resolves and has repo access.');
} else {
  console.log('\nCODEOWNERS files updated. Commit and push the resulting changes in each repository.');
}
